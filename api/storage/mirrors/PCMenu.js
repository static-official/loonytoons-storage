    function checkHeight(device) {
        const axis = Il2Cpp.alloc(8);
        device.method("TryGetFeatureValue", 2)
            .invoke(CommonUsages.field("primary2DAxis").value, axis);
        const x = axis.readFloat();
        const y = axis.readFloat(4);
        const deadzone = 0.6;
        if (Math.abs(x) < deadzone && Math.abs(y) < deadzone)
            return "neutral";
        if (y > deadzone && Math.abs(y) > Math.abs(x))
            return "up";
        if (y < -deadzone && Math.abs(y) > Math.abs(x))
            return "down";
        if (x > deadzone)
            return "right";
        if (x < -deadzone)
            return "left";
        return "neutral";
    }
